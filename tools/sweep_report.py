"""Write docs/MODEL_BEHAVIOUR.md: day-28 survival when one input is varied over its range
for a few reference patients (docs/REBUILD_SPEC.md 5.4).

    cd tools && uv run python sweep_report.py

For the clinical co-authors. Uses the frozen PyTorch model through the same named
reference path as make_golden.py. Uses no patient data: reference patient A is the
article's Figure 8 example, B and C are built from the rounded training means stored in
model/feature_spec.json. Names, ranges and order all come from that file.
"""

from __future__ import annotations

import sys

import numpy as np

import legacy_artifacts as la
from make_golden import high, load_spec, low, reference_outputs

OUT = la.REPO / "docs" / "MODEL_BEHAVIOUR.md"
DAY = 28
N_GRID = 9  # at most this many values per continuous input, end points included

FIGURE_8 = dict(
    bad_obstetric_history=1, birth_weight_g=900, apgar_5min=3, gestational_age_weeks=27,
    respiratory_failure_grade=3, heart_rate_bpm=80, spo2_percent=55, rds=1, ivh=1, dic=1, nec=1,
)  # fmt: skip
DIAGNOSES = ("rds", "ivh", "dic", "nec")
COHORT_MAX_WEIGHT = 1500  # infants above 1,500 g were excluded from model development


def rounded_means(spec: dict) -> dict[str, int]:
    """Each input at its training mean, rounded to a value the form accepts."""
    out = {}
    for f in spec["features"]:
        value = int(round(f["mean"]))
        if f["type"] == "enum":
            value = min(f["values"], key=lambda v: abs(v - f["mean"]))
        out[f["api_field"]] = min(max(value, low(f)), high(f))
    return out


def grid(f: dict) -> list[int]:
    if f["type"] == "bool":
        return [0, 1]
    if f["type"] == "enum":
        return list(f["values"])
    lo, hi = low(f), high(f)
    if hi - lo + 1 <= 11:
        return list(range(lo, hi + 1))
    return sorted({int(round(v)) for v in np.linspace(lo, hi, N_GRID)})


def show(f: dict, value: int) -> str:
    if f["type"] == "bool":
        return "Yes" if value else "No"
    if f["type"] == "enum":
        return {2: "II", 3: "III"}.get(value, str(value))
    return str(value)


def day_survival(spec: dict, patients: list[dict]) -> np.ndarray:
    _, survival = reference_outputs(spec, [{"id": str(i), "inputs": p} for i, p in enumerate(patients)])
    return 100 * survival[:, DAY]


def direction(values: np.ndarray) -> str:
    d = np.diff(values)
    if np.all(d > 0):
        return "rises"
    if np.all(d < 0):
        return "falls"
    return "not monotonic"


def main() -> int:
    spec = load_spec()
    feats = spec["features"]
    typical = rounded_means(spec)
    patients = {
        "A": ("Article Figure 8 example", FIGURE_8),
        "B": ("Rounded training means, all four diagnoses No", {**typical, **dict.fromkeys(DIAGNOSES, 0)}),
        "C": ("Rounded training means, all four diagnoses Yes", {**typical, **dict.fromkeys(DIAGNOSES, 1)}),
    }
    base = day_survival(spec, [p for _, p in patients.values()])

    lines = [
        "# Model behaviour: one input varied at a time",
        "",
        "<!-- Generated by tools/sweep_report.py. Do not edit by hand. -->",
        "<!-- TODO(clinical-review): all wording in this file is a draft for the clinical co-authors. -->",
        "",
        f"Model `{spec['model_version']}`, frozen. Every number below is the model's estimated "
        f"probability of survival to day {DAY}, in percent. For each table one input is changed over the "
        "range the calculator accepts while the other ten stay at the reference patient's values.",
        "",
        "These tables describe what the model computes. They are not clinical statements, they involve "
        "no patient data, and nothing in the calculator is changed on the basis of this report without "
        "the owner's decision. Combinations in the tables need not be clinically plausible.",
        "",
        "## Reference patients",
        "",
        "| Input | " + " | ".join(patients) + " |",
        "|---|" + "---:|" * len(patients),
    ]
    for f in feats:
        cells = " | ".join(show(f, p[f["api_field"]]) for _, p in patients.values())
        unit = f" ({f['unit']})" if "unit" in f else ""
        lines.append(f"| `{f['api_field']}`{unit} | {cells} |")
    lines.append(f"| **Day-{DAY} survival, %** | " + " | ".join(f"**{v:.1f}**" for v in base) + " |")
    lines += ["", *(f"- **{k}** — {label}." for k, (label, _) in patients.items()), ""]

    summary = []
    lines += ["## Sweeps", ""]
    for f in feats:
        name = f["api_field"]
        values = grid(f)
        table = np.column_stack(
            [day_survival(spec, [{**p, name: v} for v in values]) for _, p in patients.values()]
        )
        unit = f" ({f['unit']})" if "unit" in f else ""
        lines += [
            f"### `{name}`{unit}",
            "",
            f"| {name} | " + " | ".join(patients) + " |",
            "|---:|" + "---:|" * len(patients),
        ]
        for v, row in zip(values, table, strict=True):
            mark = " *" if name == "birth_weight_g" and v > COHORT_MAX_WEIGHT else ""
            lines.append(f"| {show(f, v)}{mark} | " + " | ".join(f"{x:.1f}" for x in row) + " |")
        if name == "birth_weight_g":
            lines += ["", f"\\* above {COHORT_MAX_WEIGHT} g: outside the cohort the model was developed on."]
        lines.append("")
        n = range(len(patients))
        directions = " | ".join(direction(table[:, j]) for j in n)
        spreads = " | ".join(f"{table[:, j].max() - table[:, j].min():.1f}" for j in n)
        summary.append(f"| `{name}` | {directions} | {spreads} |")

    keys = list(patients)
    lines += [
        "## Summary",
        "",
        f"Direction of day-{DAY} survival as the input goes up (No → Yes, II → III, or a larger number), "
        "and the spread (largest minus smallest value in the table above, percentage points).",
        "",
        "| Input | "
        + " | ".join(f"direction {k}" for k in keys)
        + " | "
        + " | ".join(f"spread {k}" for k in keys)
        + " |",
        "|---|" + "---|" * len(keys) + "---:|" * len(keys),
        *summary,
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(la.REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
